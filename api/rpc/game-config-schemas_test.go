func TestUpdateGameServerConfigFileDelegatesValidationResponse(t *testing.T) {
	t.Parallel()

	fixture := newRemoteGameConfigParityFixture(t)

	updateMsg := &xylona.UpdateGameServerConfigFileRequest{
		GameServerId: fixture.serverID,
		FilePath:     "server.properties",
		Fields: []*xylona.ConfigFieldData{
			{
				Key:   "motd",
				Value: "Still valid",
			},
			{
				Key:   "max-players",
				Value: "0",
			},
		},
	}

	localRequest := connect.NewRequest(updateMsg)
	addSessionCookieHeader(t, fixture.remoteFixture.conn, fixture.remoteFixture.secureCookie, localRequest, "user-owner")

	expected, errExpected := fixture.remoteFixture.service.UpdateGameServerConfigFile(context.Background(), localRequest)
	if errExpected != nil {
		t.Fatalf("remote UpdateGameServerConfigFile() error = %v", errExpected)
	}
	if expected.Msg.GetSuccess() {
		t.Fatal("remote UpdateGameServerConfigFile() success = true, want validation failure")
	}

	forwardedRequest := connect.NewRequest(&xylona.UpdateGameServerConfigFileRequest{
		GameServerId: updateMsg.GetGameServerId(),
		FilePath:     updateMsg.GetFilePath(),
		Fields: []*xylona.ConfigFieldData{
			{
				Key:   "motd",
				Value: "Still valid",
			},
			{
				Key:   "max-players",
				Value: "0",
			},
		},
	})
	addSessionCookieHeader(t, fixture.localFixture.conn, fixture.localFixture.secureCookie, forwardedRequest, "user-owner")

	forwarded, errForwarded := fixture.localFixture.service.UpdateGameServerConfigFile(context.Background(), forwardedRequest)
	if errForwarded != nil {
		t.Fatalf("forwarded UpdateGameServerConfigFile() error = %v, want nil transport error", errForwarded)
	}
	if forwarded.Msg.GetSuccess() {
		t.Fatal("forwarded UpdateGameServerConfigFile() success = true, want validation failure")
	}

	equal := proto.Equal(expected.Msg, forwarded.Msg)
	if !equal {
		t.Fatalf("forwarded validation payload mismatch\nexpected: %v\nforwarded: %v", expected.Msg, forwarded.Msg)
	}
}

func TestGenerateGameServerConfigFileDelegatesToFederatedServer(t *testing.T) {
	t.Parallel()

	fixture := newRemoteGameConfigParityFixture(t)

	request := connect.NewRequest(&xylona.GenerateGameServerConfigFileRequest{
		GameServerId: fixture.serverID,
		FilePath:     "generated.properties",
	})
	addSessionCookieHeader(t, fixture.localFixture.conn, fixture.localFixture.secureCookie, request, "user-owner")

	response, errGenerate := fixture.localFixture.service.GenerateGameServerConfigFile(context.Background(), request)
	if errGenerate != nil {
		t.Fatalf("GenerateGameServerConfigFile() error = %v", errGenerate)
	}
	if !response.Msg.GetSuccess() {
		t.Fatal("GenerateGameServerConfigFile() success = false, want true")
	}

	generatedPath := filepath.Join(fixture.remoteDir, "generated.properties")
	data, errRead := os.ReadFile(generatedPath)
	if errRead != nil {
		t.Fatalf("generated config file read error = %v", errRead)
	}

	if len(data) == 0 {
		t.Fatal("generated config file is empty")
	}
}

func TestGetGameServerConfigFilesReturnsTrustErrorWhenRemoteClientUnavailable(t *testing.T) {
	t.Parallel()

	fixture := newRBACRPCFixture(t)
	serverID := "server-remote-config-trust-1"

	seedRemoteNodeForRBACRPCTests(t, fixture.conn, "node-remote-peer")

	errUpsertCache := fixture.conn.UpsertRemoteServerCache(
		"remote-cache-config-trust-1",
		"node-remote-peer",
		"node-remote-peer",
		serverID,
		"Remote Config Trust",
		"OFFLINE",
		"Minecraft",
		"minecraft",
		"203.0.113.20",
		25565,
		25565,
		20,
		0,
		"world",
		"1.20.4",
		"Remote Node",
		"node-remote-peer.remote.test",
		time.Now().UTC(),
	)
	if errUpsertCache != nil {
		t.Fatalf("UpsertRemoteServerCache() error = %v", errUpsertCache)
	}

	request := connect.NewRequest(&xylona.GetGameServerConfigFilesRequest{
		GameServerId: serverID,
	})
	addSessionCookieHeader(t, fixture.conn, fixture.secureCookie, request, "user-owner")

	_, errGet := fixture.service.GetGameServerConfigFiles(context.Background(), request)
	if errGet == nil {
		t.Fatal("GetGameServerConfigFiles() error = nil, want trust failure")
	}
	if connect.CodeOf(errGet) != connect.CodeFailedPrecondition {
		t.Fatalf("GetGameServerConfigFiles() code = %v, want %v", connect.CodeOf(errGet), connect.CodeFailedPrecondition)
	}
}

func newRemoteGameConfigParityFixture(t *testing.T) *remoteGameConfigParityFixture {
	t.Helper()

	localFixture := newRBACRPCFixture(t)
	remoteFixture := newRBACRPCFixture(t)
	serverID := "server-remote-config-1"

	seedRemoteNodeForRBACRPCTests(t, localFixture.conn, "node-remote-peer")
	insertFederatedTestServer(t, remoteFixture.conn, serverID, "Remote Config", "minecraft")

	errUpdateGame := remoteFixture.conn.UpdateGameConfigSchemas("minecraft", remoteGameConfigParitySchemaJSON)
	if errUpdateGame != nil {
		t.Fatalf("UpdateGameConfigSchemas() error = %v", errUpdateGame)
	}

	remoteDir := t.TempDir()
	_, errUpdateServer := remoteFixture.conn.SQLDb.ExecContext(
		context.Background(),
		`update game_server set directory = ?, port = ?, query_port = ? where id = ?`,
		remoteDir,
		25570,
		25571,
		serverID,
	)
	if errUpdateServer != nil {
		t.Fatalf("update remote server directory error = %v", errUpdateServer)
	}

	errWrite := os.WriteFile(filepath.Join(remoteDir, "server.properties"), []byte("motd=Remote MOTD\nmax-players=20\nserver-port=25565\ncustom-key=custom-value\n"), 0o600)
	if errWrite != nil {
		t.Fatalf("write remote config file error = %v", errWrite)
	}

	errCreateGrant := remoteFixture.conn.CreateFederatedAccessGrant(
		"fed-config-grant-1",
		serverID,
		"node-local",
		"user-owner",
		"Owner User",
		"admin",
		"user-owner",
	)
	if errCreateGrant != nil {
		t.Fatalf("CreateFederatedAccessGrant() error = %v", errCreateGrant)
	}

	errUpsertCache := localFixture.conn.UpsertRemoteServerCache(
		"remote-cache-config-1",
		"node-remote-peer",
		"node-remote-peer",
		serverID,
		"Remote Config",
		"OFFLINE",
		"Minecraft",
		"minecraft",
		"203.0.113.12",
		25570,
		25571,
		20,
		0,
		"world",
		"1.20.4",
		"Remote Node",
		"node-remote-peer.remote.test",
		time.Now().UTC(),
	)
	if errUpsertCache != nil {
		t.Fatalf("UpsertRemoteServerCache() error = %v", errUpsertCache)
	}

	remoteService := FederationService{
		ctx: context.Background(),
		db:  remoteFixture.conn,
	}

	mux := http.NewServeMux()
	path, handler := xylonaconnect.NewFederationHandler(&remoteService)
	mux.Handle(path, injectFederationPeerIdentity("node-local", handler))

	remoteServer := httptest.NewServer(mux)
	t.Cleanup(remoteServer.Close)

	localFixture.service.remoteFederationClientFactory = func(_ *models.Node, _ string) (xylonaconnect.FederationClient, error) {
		return xylonaconnect.NewFederationClient(remoteServer.Client(), remoteServer.URL), nil
	}

	return &remoteGameConfigParityFixture{
		localFixture:  localFixture,
		remoteFixture: remoteFixture,
		remoteServer:  remoteServer,
		remoteDir:     remoteDir,
		serverID:      serverID,
	}
}
