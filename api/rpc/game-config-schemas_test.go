func TestGetGameServerConfigFilesDelegatesToFederatedServer(t *testing.T) {
	t.Parallel()

	fixture := newRemoteGameConfigParityFixture(t)

	localRequest := connect.NewRequest(&xylona.GetGameServerConfigFilesRequest{
		GameServerId: fixture.serverID,
	})
	addSessionCookieHeader(t, fixture.remoteFixture.conn, fixture.remoteFixture.secureCookie, localRequest, "user-owner")

	expected, errExpected := fixture.remoteFixture.service.GetGameServerConfigFiles(context.Background(), localRequest)
	if errExpected != nil {
		t.Fatalf("remote GetGameServerConfigFiles() error = %v", errExpected)
	}

	forwardedRequest := connect.NewRequest(&xylona.GetGameServerConfigFilesRequest{
		GameServerId: fixture.serverID,
	})
	addSessionCookieHeader(t, fixture.localFixture.conn, fixture.localFixture.secureCookie, forwardedRequest, "user-owner")

	forwarded, errForwarded := fixture.localFixture.service.GetGameServerConfigFiles(context.Background(), forwardedRequest)
	if errForwarded != nil {
		t.Fatalf("forwarded GetGameServerConfigFiles() error = %v", errForwarded)
	}

	equal := proto.Equal(expected.Msg, forwarded.Msg)
	if !equal {
		t.Fatalf("forwarded config file list mismatch\nexpected: %v\nforwarded: %v", expected.Msg, forwarded.Msg)
	}
}

